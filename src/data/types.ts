/**
 * Central schema for project content and the generated manifest.
 *
 * This file is the single source of truth for:
 * - the manifest schema (Section 5.3 of IMPLEMENTATION_PLAN.md)
 * - the supported file extensions (Section 4.3)
 * - the project ID and date conventions (Section 4.1)
 *
 * Build-time code (scripts/*.mjs) and browser-side code must both derive
 * their behavior from these definitions. The schema is versioned via
 * `MANIFEST_SCHEMA_VERSION`; bump it whenever the shape changes.
 */

/**
 * Version of the manifest schema. Build-time validation and the browser
 * bundle must agree on this value.
 */
export const MANIFEST_SCHEMA_VERSION = 1;

/**
 * Supported gallery image extensions, without the leading dot.
 * Keep this list in sync with Section 4.3 of IMPLEMENTATION_PLAN.md.
 * SVG is deliberately excluded until security and rendering tests exist.
 */
export const SUPPORTED_IMAGE_EXTENSIONS = [
  "jpg",
  "jpeg",
  "png",
  "webp",
  "avif",
  "gif",
] as const;

/**
 * Supported gallery text extensions, without the leading dot.
 * Text is always rendered as plain text in the first release.
 */
export const SUPPORTED_TEXT_EXTENSIONS = ["txt", "md", "markdown"] as const;

export type ImageExtension = (typeof SUPPORTED_IMAGE_EXTENSIONS)[number];
export type TextExtension = (typeof SUPPORTED_TEXT_EXTENSIONS)[number];

/**
 * An asset that belongs to a project and appears in its gallery.
 * `name` is the basename without extension; `path` is relative to the
 * deployed site root (after base-path normalization happens at build time).
 */
export type ProjectAsset = {
  type: "image" | "text";
  name: string;
  path: string;
  mimeType: string;
};

/**
 * A single project. `id` equals the folder date (`YYYY-MM-DD`), which is
 * the canonical project date — never derived from file metadata.
 */
export type Project = {
  id: string;
  date: string;
  description: string;
  featuredImage: string;
  assets: ProjectAsset[];
};

/**
 * The manifest generated by the build and embedded into dist/index.html.
 */
export type ProjectManifest = {
  schemaVersion: typeof MANIFEST_SCHEMA_VERSION;
  projects: Project[];
};

/**
 * Strict `YYYY-MM-DD` folder-date convention (Section 4.1).
 * Kept here so validation and display code share one definition.
 */
export const PROJECT_DATE_PATTERN = /^\d{4}-\d{2}-\d{2}$/;

/**
 * The required metadata file for every project (Section 4.2).
 */
export const REQUIRED_DESCRIPTION_FILE = "0.txt";

/**
 * Basename (without extension) of the featured timeline image (Section 4.2).
 */
export const FEATURED_IMAGE_BASENAME = "0";
